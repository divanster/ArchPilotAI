def test_project_isolation(
    client: TestClient, engine: Engine, mixed: tuple[str, Path], workspace: str, tmp_path: Path
) -> None:
    pid, _clone = mixed
    other = client.post("/api/projects", json={"name": "Other"}).json()["id"]
    connect(
        engine,
        workspace,
        other,
        remote_of(tmp_path, {"lib/billing.py": "def charge() -> None:\n    pass\n"}, "other"),
        clone_folder="other-clone",
    )
    assert mcp_tools.find_symbol(ctx(engine), other, "charge")["matches"]
    assert mcp_tools.find_symbol(ctx(engine), other, "Order")["matches"] == []
    assert mcp_tools.find_symbol(ctx(engine), pid, "charge")["matches"] == []
    assert mcp_tools.search_repository(ctx(engine), pid, "charge")["matches"] == []

    # A map copied to another project's cache file is not trusted.
    cache = Path(workspace, ".archpilot", "repo-maps")
    shutil.copy(cache / f"{pid}.json", cache / f"{other}.json")
    assert maps(engine, workspace).load(uuid.UUID(other)) is None
    with pytest.raises(ToolInputError, match="Unknown project_id"):
        summary_of(engine, str(uuid.uuid4()))
    with pytest.raises(ToolInputError, match="not connected|No external repository"):
        summary_of(engine, client.post("/api/projects", json={"name": "Bare"}).json()["id"])


def test_agent_reads_only_its_own_projects_repository(
    client: TestClient,
    engine: Engine,
    mixed: tuple[str, Path],
    workspace: str,
    tmp_path: Path,
    world: World,
) -> None:
    pid, _clone = mixed
    other = client.post("/api/projects", json={"name": "Other"}).json()["id"]
    connect(
        engine,
        workspace,
        other,
        remote_of(tmp_path, {"lib/billing.py": "def charge() -> None:\n    pass\n"}, "other"),
        clone_folder="other-clone",
    )
    run, provider = play(
        client,
        world,
        [
            action("get_repo_summary"),
            action("find_symbol", name="charge"),
            action("find_symbol", name="Order", project_id=other),
            action("get_file_dependants", path="backend/orders/models.py"),
            action("find_references", name="place_order"),
            action("search_repository", query="fetchOrders", prefix="frontend"),
            finish(),
        ],
    )
    steps = run["steps"]
    assert [s["tool"] for s in steps[:6]] == [
        "get_repo_summary",
        "find_symbol",
        "find_symbol",
        "get_file_dependants",
        "find_references",
        "search_repository",
    ]
    assert all(s["tier"] == "read" for s in steps[:6])
    assert steps[0]["error_code"] is None and steps[1]["error_code"] is None
    assert steps[2]["error_code"] is not None  # project_id is not an agent argument
    assert [s["error_code"] for s in steps[3:6]] == [None, None, None]
    results = context_of(provider.requests[2].prompt)["last_results"]
    assert "0 definition(s)" in json.dumps(results)  # "charge" lives in the other project

    brief = context_of(provider.requests[0].prompt)["task"]["repository"]
    assert brief["scan_commit"] == brief["head_commit"] and brief["stale"] is False
    assert brief["branch"] == "main"
    assert "never authority" in brief["note"]
    assert "Django" in brief["summary"]["frameworks"]
    assert {i["path"] for i in brief["instruction_files"]} >= {"AGENTS.md", "README.md"}
    assert len(json.dumps(brief)) <= service_module.CONTEXT_CHARS
    assert len(brief["related_files"]) <= service_module.CONTEXT_FILES
    assert "instruction files" in provider.requests[0].system_prompt


