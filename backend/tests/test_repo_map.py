def write_tree(root: Path, files: dict[str, str | bytes]) -> None:
    for rel, content in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_bytes(content.encode("utf-8"))


def init_repo(root: Path, files: dict[str, str | bytes]) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    git(root, "init", "-q", "-b", "main")
    git(root, "config", "core.autocrlf", "false")
    write_tree(root, files)
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "init")
    return root


def remote_of(tmp_path: Path, files: dict[str, str | bytes], name: str = "remote") -> str:
    """A local bare repository holding `files` on main. Never a real remote."""
    seed = init_repo(tmp_path / f"{name}-seed", files)
    bare = tmp_path / f"{name}.git"
    subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(bare)], check=True)
    git(seed, "push", "-q", str(bare), "main")
    return bare.as_posix()


def commit_file(clone: Path, rel: str, content: str) -> str:
    write_tree(clone, {rel: content})
    git(clone, "add", "-A")
    git(clone, "commit", "-q", "-m", f"add {rel}")
    return git(clone, "rev-parse", "HEAD").strip()


