def test_repository_tools_are_read_tier_for_both_audiences() -> None:
    registry = get_registry()
    for name in NEW_TOOLS:
        for audience in ("mcp", "agent"):
            tool = registry.get(audience, name)
            assert tool.tier == "read" and not tool.needs_execution
        agent_fields = set(registry.get("agent", name).args_model.model_fields)
        assert "project_id" not in agent_fields  # the run's project, never the model's choice
        assert "project_id" in registry.get("mcp", name).args_model.model_fields
    server = create_server(ToolContext(lambda: None))  # type: ignore[arg-type,return-value]
    import asyncio

    listed = {t.name: t for t in asyncio.run(server.list_tools())}
    for name in NEW_TOOLS:
        assert "project_id" in listed[name].inputSchema["required"]
    with pytest.raises(ToolInputError, match="Invalid arguments"):
        registry.call("mcp", "search_repository", {"project_id": "x", "query": "a"}, None)


