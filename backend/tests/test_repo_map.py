def test_domain_module_cannot_run_anything() -> None:
    banned = {"subprocess", "os", "importlib", "runpy", "shutil", "pathlib", "socket"}
    for name in ("domain/repo_map.py", "services/repo_map.py"):
        tree = ast.parse((APP_DIR / name).read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import | ast.ImportFrom):
                modules = [a.name for a in node.names] + [getattr(node, "module", None) or ""]
                roots = {m.split(".")[0] for m in modules}
                allowed = {"os", "pathlib"} if name.startswith("services") else set()
                assert not (roots & (banned - allowed)), (name, modules)
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
                assert node.func.id not in {"exec", "eval", "compile", "__import__"}, name


def test_read_head_without_git(tmp_path: Path) -> None:
    repo = init_repo(tmp_path / "r", {"a.py": "x = 1\n"})
    expected = git(repo, "rev-parse", "HEAD").strip()
    assert read_head(repo) == ("main", expected)
    git(repo, "pack-refs", "--all")
    assert read_head(repo) == ("main", expected)
    git(repo, "checkout", "-q", "--detach")
    assert read_head(repo) == (None, expected)
    assert read_head(tmp_path / "missing") == (None, None)


