def test_agent_context_is_a_bounded_neighbourhood(engine: Engine, mixed: tuple[str, Path]) -> None:
    pid, clone = mixed
    repo_map = maps_for(engine, clone, pid)
    big = dict(repo_map.data)
    big["instructions"] = [
        {"path": "AGENTS.md", "chars": 50_000, "truncated": True, "content": "y" * 4000},
        {"path": "README.md", "chars": 4000, "truncated": False, "content": "z" * 4000},
    ]
    block = agent_context(
        service_module.RepoMap(big), "main", repo_map.commit, "Add a refund to the Order service"
    )
    assert len(json.dumps(block)) <= service_module.CONTEXT_CHARS
    related = [f["path"] for f in block["related_files"]]
    assert related and related[0].startswith("backend/orders/")
    assert len(related) <= service_module.CONTEXT_FILES
    assert "backend/orders/models.py" in related
    models = next(f for f in block["related_files"] if f["path"] == "backend/orders/models.py")
    assert "backend/orders/services.py" in models["dependants"]
    assert all(i["truncated"] for i in block["instruction_files"])
    assert len(block["summary"]["languages"]) <= 8


